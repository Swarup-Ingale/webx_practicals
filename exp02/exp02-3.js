// Calculator

"use strict";
function add(a, b) {
    return a + b;
}
function sub(a, b) {
    return a - b;
}
function mul(a, b) {
    return a * b;
}
function div(a, b) {
    return a / b;
}
let num1 = 10;
let num2 = 20;
console.log("addition : ", add(num1, num2));
console.log("subtraction : ", sub(num1, num2));
console.log("multiplication : ", mul(num1, num2));
console.log("division : ", div(num1, num2));
